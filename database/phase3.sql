CREATE TABLE IF NOT EXISTS learning_media (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 camp_id BIGINT UNSIGNED NOT NULL,
 title VARCHAR(200) NOT NULL, category VARCHAR(100) NOT NULL,
 content MEDIUMTEXT NOT NULL, external_url VARCHAR(2000) NOT NULL DEFAULT '',
 visibility ENUM('public','staff','draft') NOT NULL DEFAULT 'draft',
 file_key VARCHAR(80) NULL, file_mime VARCHAR(100) NULL,
 version INT UNSIGNED NOT NULL DEFAULT 0,
 FOREIGN KEY (camp_id) REFERENCES camps(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS games (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 camp_id BIGINT UNSIGNED NOT NULL,
 name VARCHAR(200) NOT NULL, description TEXT NOT NULL, rules TEXT NOT NULL,
 rounds SMALLINT UNSIGNED NOT NULL, duration_seconds INT UNSIGNED NOT NULL,
 status ENUM('draft','active','archived') NOT NULL DEFAULT 'draft',
 version INT UNSIGNED NOT NULL DEFAULT 0,
 FOREIGN KEY (camp_id) REFERENCES camps(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS score_criteria (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 game_id BIGINT UNSIGNED NOT NULL,
 name VARCHAR(100) NOT NULL,
 score_type ENUM('integer','decimal') NOT NULL,
 min_score DECIMAL(12,2) NOT NULL, max_score DECIMAL(12,2) NOT NULL,
 position SMALLINT UNSIGNED NOT NULL,
 FOREIGN KEY (game_id) REFERENCES games(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
