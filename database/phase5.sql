ALTER TABLE staff_assignments ADD COLUMN IF NOT EXISTS field_no SMALLINT UNSIGNED NULL;
CREATE TABLE IF NOT EXISTS match_score_versions (
 match_id BIGINT UNSIGNED PRIMARY KEY,
 version INT UNSIGNED NOT NULL DEFAULT 0,
 updated_by BIGINT UNSIGNED NULL,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY (match_id) REFERENCES competition_matches(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS score_entries (
 entry_id BIGINT UNSIGNED NOT NULL,
 criterion_no SMALLINT UNSIGNED NOT NULL,
 amount_cents BIGINT NOT NULL,
 PRIMARY KEY(entry_id,criterion_no),
 FOREIGN KEY (entry_id) REFERENCES competition_entries(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS score_revisions (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 match_id BIGINT UNSIGNED NOT NULL,
 version INT UNSIGNED NOT NULL,
 actor_id BIGINT UNSIGNED NOT NULL,
 scores_json LONGTEXT NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY match_version (match_id,version),
 FOREIGN KEY (match_id) REFERENCES competition_matches(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS ranking_settings (
 camp_id BIGINT UNSIGNED PRIMARY KEY,
 mode ENUM('raw','normalized') NOT NULL,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY(camp_id) REFERENCES camps(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
