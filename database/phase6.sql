CREATE TABLE IF NOT EXISTS evaluations (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 camp_id BIGINT UNSIGNED NOT NULL,
 submission_token CHAR(64) NOT NULL UNIQUE,
 satisfaction TINYINT UNSIGNED NOT NULL,
 activities TINYINT UNSIGNED NOT NULL,
 staff_rating TINYINT UNSIGNED NOT NULL,
 activity_level ENUM('easy','appropriate','difficult') NOT NULL,
 learned TEXT NOT NULL,
 feedback TEXT NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(camp_id) REFERENCES camps(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
